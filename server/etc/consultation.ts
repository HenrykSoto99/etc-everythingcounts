const MAX_TEXT = 4000;
const MAX_MESSAGES = 100;
const MAX_MODEL_HISTORY = 20;
const lockTails = new Map<string, Promise<void>>();

function httpError(status: number, message: string): HttpError {
  const error = new Error(message) as HttpError;
  error.status = status;
  return error;
}

function clean(value: unknown, max = MAX_TEXT): string {
  return typeof value === "string" ? value.trim().slice(0, max) : "";
}

function languageOf(value: unknown): ConsultationLanguage {
  if (value === "es" || value === "en") return value;
  throw httpError(400, "language debe ser es o en.");
}

function fallbackReason(
  language: ConsultationLanguage,
  kind: "quota" | "unsafe" | "provider" | "success",
  providerMessage?: string
): string {
  if (kind === "quota")
    return language === "es"
      ? "Límite diario de IA alcanzado; se usa contenido aprobado."
      : "The daily AI limit was reached; approved content is used.";
  if (kind === "unsafe")
    return language === "es"
      ? "La respuesta del proveedor no pasó la revisión de alcance; se usa contenido aprobado."
      : "The provider response failed the scope review; approved content is used.";
  if (kind === "success")
    return language === "es"
      ? "Respuesta generada por el proveedor configurado."
      : "Response generated by the configured provider.";
  if (language === "en")
    return "The configured provider failed; approved content is used.";
  return `${providerMessage ?? "Error del proveedor"} Se usa contenido aprobado.`;
}

function scopeBusinessType(
  workspace: WorkspaceWithBusinessType
): BusinessType | null {
  if (workspace.segment !== "pymes") return null;
  if (!isBusinessType(workspace.businessType))
    throw httpError(409, "El espacio PYMES no tiene un subtipo válido.");
  return workspace.businessType;
}

export function consultationScopeFromContext(
  ctx: AuthContext
): ConsultationScope {
  const workspace = ctx.workspace as WorkspaceWithBusinessType;
  if (!SEGMENTS.includes(workspace.segment))
    throw httpError(409, "El espacio tiene un segmento inválido.");
  return {
    segment: workspace.segment,
    businessType: scopeBusinessType(workspace),
  };
}

export function validateConsultationScope(
  actual: ConsultationScope,
  requestedSegment: unknown,
  requestedBusinessType: unknown
): ConsultationScope {
  if (
    typeof requestedSegment !== "string" ||
    !SEGMENTS.includes(requestedSegment as Segment)
  )
    throw httpError(400, "segment inválido.");
  if (requestedSegment !== actual.segment)
    throw httpError(403, "El segmento no coincide con el espacio actual.");

  if (requestedBusinessType !== undefined && requestedBusinessType !== null) {
    if (!isBusinessType(requestedBusinessType))
      throw httpError(400, "businessType inválido.");
    if (requestedBusinessType !== actual.businessType)
      throw httpError(403, "El subtipo no coincide con el espacio actual.");
  } else if (actual.businessType !== null && requestedBusinessType === null) {
    throw httpError(403, "El subtipo no coincide con el espacio actual.");
  }
  return actual;
}

function normalized(value: string): string {
  return value
    .toLocaleLowerCase("es")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

function hasTerm(value: string, term: string): boolean {
  return new RegExp(`(?:^|[^a-z0-9])${term}(?:$|[^a-z0-9])`, "i").test(value);
}

